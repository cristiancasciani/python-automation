def folder_name(key: str) -> str:
    """Name on disk of a category folder ('Invoices' -> 'Fatture' in Italian)."""
    return t(f'dir.{key}')


def all_folder_names() -> set[str]:
    """Folder names in every language: Ordo never moves its own folders."""
    return {v for lang in LANGS for k, v in TEXTS[lang].items() if k.startswith('dir.')}


def set_lang(lang: str):
    global _lang
    if lang in LANGS:
        _lang = lang


def get_lang() -> str:
    return _lang


def t(key: str, **kw) -> str:
    text = TEXTS[_lang].get(key) or TEXTS['en'].get(key, key)
    return text.format(**kw) if kw else text


def money(v) -> str:
    """€ 1,234.56 in English, € 1.234,56 in Italian; '—' when missing."""
    if v is None:
        return '—'
    s = f'{v:,.2f}'
    if _lang == 'it':
        s = s.replace(',', 'X').replace('.', ',').replace('X', '.')
    return f'€ {s}'
